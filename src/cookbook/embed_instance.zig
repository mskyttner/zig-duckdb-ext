///! Cookbook: instances, attached databases and the catalog, from a program that hosts DuckDB, and an audit of how well
///! the functions of an instance are documented (`zig build cookbook-embed-instance`).
///!
///! **Not from an extension**, like `embed_sql.zig` (whose session helpers this file uses): an extension is given a context,
///! never an instance, a connection or an environment. A host creates and manages them:
///!
///!   environment                      the root every instance hangs from; `environment_get_instance_count` counts them, and
///!                                    `environment_destroy` is refused while any is alive
///!   instance_create_with_options     startup options, as SQL `SET` writes them: the only way to choose `allow_unsigned_extensions`
///!                                    or `access_mode`; a name that nothing claims fails the creation, and so does an option that
///!                                    needs a running instance
///!   instance_attach / _detach / _set_default     like `ATTACH`, `DETACH` and `USE` for connections made afterwards; attach options
///!                                    are the `(KEY value)` list of `ATTACH` (READ_ONLY); a path attached anywhere in the
///!                                    environment is in use
///!   connection_describe_table        a table's columns, from the catalog, without a query: the resolved name, whether its catalog
///!                                    is read-only, and for every column its name, type and whether it has a default or is generated
///!
///! **The audit.** `duckdb_functions()` has, for every function of the instance, a description, examples, categories and the
///! names of its parameters, and `extension_name` says where it came from (a path, for an extension loaded from a file). The audit
///! counts, for each extension of the instance, how many functions have each of them, and checks that the functions of the two
///! v2 extensions are all documented and have real parameter names (not `col0` or `a0`), and that **every example runs**.
const std = @import("std");
const v2 = @import("duckdb_v2_api");
const helpers = @import("v2_helpers");
const host = @import("embed_sql.zig");
// Generated by build.zig from the archives it linked: here the capability `loadable_extensions`, without which `LOAD` of a
// file fails ("this build does not link the loadable_extensions library"). It is registered before any instance exists.
const static_extensions = @import("static_extensions");

const Call = host.Call;
const Session = host.Session;
const view = host.view;
const expectEqual = host.expectEqual;
const expectInt = host.expectInt;
const expectFailure = host.expectFailure;

extern "c" fn remove(path: [*:0]const u8) c_int;

fn str(s: []const u8) v2.duckdb_v2_str {
    return helpers.str(s);
}

/// The text of a one-value query.
fn scalar(arena: std.mem.Allocator, s: *Session, sql: []const u8) ![]const u8 {
    return host.query(arena, s, sql);
}

/// The names of the attached databases, comma-separated and sorted. (No string_agg here: the aggregate functions beyond
/// the built-in few live in the `core_functions` extension, which this program does not link.)
fn databases(arena: std.mem.Allocator, s: *Session) ![]const u8 {
    const rows = (try host.runAll(arena, s, "SELECT database_name FROM duckdb_databases() WHERE NOT internal ORDER BY database_name"))[0].rows;
    var out: std.ArrayList(u8) = .empty;
    for (rows, 0..) |row, i| {
        if (i > 0) try out.append(arena, ',');
        try out.appendSlice(arena, row[0]);
    }
    return out.items;
}

/// The database a connection creates unqualified tables in, found by creating one (`current_database()` is a macro over
/// functions of the `core_functions` extension, which this program does not link).
fn defaultDatabase(arena: std.mem.Allocator, s: *Session) ![]const u8 {
    _ = try host.runAll(arena, s, "CREATE TABLE zig_cookbook_probe (i INTEGER)");
    const rows = (try host.runAll(arena, s, "SELECT database_name FROM duckdb_tables() WHERE table_name = 'zig_cookbook_probe'"))[0].rows;
    _ = try host.runAll(arena, s, "DROP TABLE zig_cookbook_probe");
    return rows[0][0];
}

/// A new connection to the session's instance, as a session of its own: the default database is the one at the time.
fn connection(s: *const Session) !Session {
    var other = s.*;
    var c: Call = .{};
    try c.ok(v2.duckdb_v2_connection_create(s.instance, &other.conn, c.err()));
    errdefer _ = v2.duckdb_v2_connection_destroy(&other.conn);
    try c.ok(v2.duckdb_v2_connection_get_factory(other.conn, &other.factory, c.err()));
    return other;
}

fn drop(s: *Session) void {
    _ = v2.duckdb_v2_connection_destroy(&s.conn);
}

pub fn main(init: std.process.Init) !void {
    var arena_state = std.heap.ArenaAllocator.init(std.heap.c_allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    var args = init.minimal.args.iterate();
    _ = args.next();
    const v2_extension = args.next() orelse return error.MissingArgument;
    const cookbook_extension = args.next() orelse return error.MissingArgument;

    if (static_extensions.registerAll() != 0) return error.RegisterFailed;
    run(arena, v2_extension, cookbook_extension) catch |e| {
        if (e == error.DuckDb) std.debug.print("DuckDB error {t}: {s}\n", .{ host.error_code, host.error_text });
        return e;
    };
    std.debug.print("all {d} instance and catalog checks passed\n", .{host.checks});
}

fn run(arena: std.mem.Allocator, v2_extension: []const u8, cookbook_extension: []const u8) !void {
    try environments(arena);
    try attaching(arena);
    try catalog(arena);
    try audit(arena, v2_extension, cookbook_extension);
}

// --- environment and instances -----------------------------------------------------------------------------------------

fn environments(arena: std.mem.Allocator) !void {
    _ = arena;
    var c: Call = .{};
    var env: v2.duckdb_v2_environment_handle = undefined;
    try c.ok(v2.duckdb_v2_environment_create(&env, c.err()));
    var count: u64 = 99;
    try c.ok(v2.duckdb_v2_environment_get_instance_count(env, &count, c.err()));
    try expectInt("a new environment has no instance", 0, count);

    var a: v2.duckdb_v2_instance_handle = undefined;
    var b: v2.duckdb_v2_instance_handle = undefined;
    try c.ok(v2.duckdb_v2_instance_create(env, &a, c.err()));
    try c.ok(v2.duckdb_v2_instance_create(env, &b, c.err()));
    try c.ok(v2.duckdb_v2_environment_get_instance_count(env, &count, c.err()));
    try expectInt("two instances", 2, count);

    // The environment cannot go while an instance is alive; the count is how to find the one that leaked.
    // (This call has no error slot: the code is all it says.)
    var env_again = env;
    try expectEqual("environment_destroy with live instances", "ERROR_RESOURCE_IN_USE", @tagName(v2.duckdb_v2_environment_destroy(&env_again)));
    _ = v2.duckdb_v2_instance_destroy(&b);
    try c.ok(v2.duckdb_v2_environment_get_instance_count(env, &count, c.err()));
    try expectInt("one instance left", 1, count);

    // Startup options, in the textual form SQL SET accepts. `threads` could be set later too; the creation shows they
    // are applied before the instance runs.
    var opt_names = [_]v2.duckdb_v2_str{str("threads")};
    var opt_values = [_]v2.duckdb_v2_str{str("2")};
    var configured: v2.duckdb_v2_instance_handle = undefined;
    try c.ok(v2.duckdb_v2_instance_create_with_options(env, &opt_names, &opt_values, 1, &configured, c.err()));
    {
        var s: Session = undefined;
        s.env = env;
        s.instance = configured;
        const memory = str(":memory:");
        try c.ok(v2.duckdb_v2_instance_attach(configured, null, &memory, null, true, c.err()));
        try c.ok(v2.duckdb_v2_connection_create(configured, &s.conn, c.err()));
        defer _ = v2.duckdb_v2_connection_destroy(&s.conn);
        try c.ok(v2.duckdb_v2_connection_get_factory(s.conn, &s.factory, c.err()));
        try c.ok(v2.duckdb_v2_factory_create_type_from_id(s.factory, .LOGICAL_TYPE_ID_VARCHAR, null, null, 0, &s.varchar, c.err()));
        defer _ = v2.duckdb_v2_logical_type_destroy(&s.varchar);
        var arena_state = std.heap.ArenaAllocator.init(std.heap.c_allocator);
        defer arena_state.deinit();
        try expectEqual("a startup option is applied", "2", try scalar(arena_state.allocator(), &s, "SELECT value FROM duckdb_settings() WHERE name = 'threads'"));
    }
    _ = v2.duckdb_v2_instance_destroy(&configured);

    // A name nothing claims fails the creation, with the name; so does an option that needs a running instance.
    var bad_names = [_]v2.duckdb_v2_str{str("no_such_option")};
    var bad_values = [_]v2.duckdb_v2_str{str("1")};
    var bad: v2.duckdb_v2_instance_handle = undefined;
    try expectFailure("an unknown startup option", blk: {
        var c2: Call = .{};
        break :blk c2.ok(v2.duckdb_v2_instance_create_with_options(env, &bad_names, &bad_values, 1, &bad, c2.err()));
    }, .ERROR_INPUT_INVALID, "no_such_option");
    var late_names = [_]v2.duckdb_v2_str{str("allowed_directories")};
    var late_values = [_]v2.duckdb_v2_str{str("['/tmp']")};
    try expectFailure("an option that needs a running instance", blk: {
        var c2: Call = .{};
        break :blk c2.ok(v2.duckdb_v2_instance_create_with_options(env, &late_names, &late_values, 1, &bad, c2.err()));
    }, .ERROR_INPUT_INVALID, "");

    _ = v2.duckdb_v2_instance_destroy(&a);
    try c.ok(v2.duckdb_v2_environment_get_instance_count(env, &count, c.err()));
    try expectInt("no instance left", 0, count);
    try c.ok(v2.duckdb_v2_environment_destroy(&env));
}

// --- attaching, detaching, the default ------------------------------------------------------------------------------------

fn attaching(arena: std.mem.Allocator) !void {
    var s = try Session.open();
    defer s.close();
    var c: Call = .{};

    // The names of the attached databases, as SQL sees them.
    try expectEqual("the database of Session.open", "memory", try databases(arena, &s));

    // `:memory:` twice, side by side, under names. The first call made one the default for connections made afterwards.
    const a = str("a");
    const b = str("b");
    const memory = str(":memory:");
    try c.ok(v2.duckdb_v2_instance_attach(s.instance, &a, &memory, null, false, c.err()));
    try c.ok(v2.duckdb_v2_instance_attach(s.instance, &b, &memory, null, false, c.err()));
    try expectEqual("attached", "a,b,memory", try databases(arena, &s));

    {
        var other = try connection(&s);
        defer drop(&other);
        try expectEqual("the default is where it was", "memory", try defaultDatabase(arena, &other));
    }
    // A default for connections made from now on; a connection that exists keeps its own.
    try c.ok(v2.duckdb_v2_instance_set_default(s.instance, &b, c.err()));
    {
        var other = try connection(&s);
        defer drop(&other);
        try expectEqual("set_default", "b", try defaultDatabase(arena, &other));
        try expectEqual("an older connection keeps its default", "memory", try defaultDatabase(arena, &s));
    }

    // A name that is attached already, a name that is not.
    try expectFailure("attaching a name twice", blk: {
        var c2: Call = .{};
        break :blk c2.ok(v2.duckdb_v2_instance_attach(s.instance, &a, &memory, null, false, c2.err()));
    }, .ERROR_QUERY_BINDER, "already exists");
    const nothing = str("nothing");
    try expectFailure("set_default of an unknown name", blk: {
        var c2: Call = .{};
        break :blk c2.ok(v2.duckdb_v2_instance_set_default(s.instance, &nothing, c2.err()));
    }, .ERROR_INPUT_INVALID, "");
    try expectFailure("detaching an unknown name", blk: {
        var c2: Call = .{};
        break :blk c2.ok(v2.duckdb_v2_instance_detach(s.instance, &nothing, c2.err()));
    }, .ERROR_INPUT_INVALID, "");

    // Unlike SQL, the default can be detached: connections made after that have none until another is named.
    try c.ok(v2.duckdb_v2_instance_detach(s.instance, &b, c.err()));
    try expectEqual("detached", "a,memory", try databases(arena, &s));
    try c.ok(v2.duckdb_v2_instance_set_default(s.instance, &a, c.err()));
    {
        var other = try connection(&s);
        defer drop(&other);
        try expectEqual("a new default", "a", try defaultDatabase(arena, &other));
    }

    // A file: the name comes from the path up to its first dot, as SQL ATTACH without AS does it. Read-only is an attach
    // option, set like the `(READ_ONLY)` of ATTACH, and a path can be attached once in the whole environment.
    const path_text = "/tmp/zig_cookbook_instance.sales.2024.db";
    _ = remove(path_text);
    _ = remove(path_text ++ ".wal");
    const path = str(path_text);
    try c.ok(v2.duckdb_v2_instance_attach(s.instance, null, &path, null, false, c.err()));
    try expectEqual("the name derived from the path", "a,memory,zig_cookbook_instance", try databases(arena, &s));
    _ = try host.runAll(arena, &s, "CREATE TABLE zig_cookbook_instance.t AS SELECT 42 AS answer");
    try expectFailure("the same path again", blk: {
        var c2: Call = .{};
        const again = str("again");
        break :blk c2.ok(v2.duckdb_v2_instance_attach(s.instance, &again, &path, null, false, c2.err()));
    }, .ERROR_RESOURCE_IN_USE, "");

    // Detached, it is written to the file, and can be attached again read-only.
    const derived = str("zig_cookbook_instance");
    try c.ok(v2.duckdb_v2_instance_detach(s.instance, &derived, c.err()));
    var options: v2.duckdb_v2_attach_options_handle = undefined;
    try c.ok(v2.duckdb_v2_attach_options_create(s.instance, &options, c.err()));
    defer _ = v2.duckdb_v2_attach_options_destroy(&options);
    const read_only = str("READ_ONLY");
    const yes = str("true");
    try c.ok(v2.duckdb_v2_attach_options_set(options, &read_only, &yes, c.err()));
    const ro = str("ro");
    try c.ok(v2.duckdb_v2_instance_attach(s.instance, &ro, &path, options, false, c.err()));
    try expectEqual("what was written", "42", try scalar(arena, &s, "SELECT answer FROM ro.t"));
    try expectFailure("writing to a read-only database", host.runAll(arena, &s, "INSERT INTO ro.t VALUES (1)"), .ERROR_INPUT_INVALID, "attached in read-only mode");
    try c.ok(v2.duckdb_v2_instance_detach(s.instance, &ro, c.err()));
    _ = remove(path_text);
    _ = remove(path_text ++ ".wal");
}

// --- the catalog -----------------------------------------------------------------------------------------------------------

/// A type as SQL writes it.
fn typeText(arena: std.mem.Allocator, ty: v2.duckdb_v2_logical_type_handle, c: *Call) ![]const u8 {
    var need: u64 = 0;
    const no_buffer: ?[*]u8 = null;
    _ = no_buffer;
    var probe: [1]u8 = undefined;
    // First the length (the call fails with it when the buffer is too small), then the text.
    _ = v2.duckdb_v2_logical_type_to_text(ty, &probe, 0, &need, null);
    const buffer = try arena.alloc(u8, need + 1);
    var written: u64 = 0;
    try c.ok(v2.duckdb_v2_logical_type_to_text(ty, buffer.ptr, buffer.len, &written, c.err()));
    return buffer[0..written];
}

fn qnameText(arena: std.mem.Allocator, name: v2.duckdb_v2_qname_handle, c: *Call) ![]const u8 {
    var need: u64 = 0;
    var probe: [1]u8 = undefined;
    _ = v2.duckdb_v2_qname_render(name, &probe, 0, &need, null);
    const buffer = try arena.alloc(u8, need + 1);
    var written: u64 = 0;
    try c.ok(v2.duckdb_v2_qname_render(name, buffer.ptr, buffer.len, &written, c.err()));
    return buffer[0..written];
}

/// The columns of a table as "name TYPE [default] [generated]" words, and the resolved name and read-only flag in front.
fn describe(arena: std.mem.Allocator, s: *Session, name: []const u8) ![]const u8 {
    var c: Call = .{};
    const text = str(name);
    var parsed: v2.duckdb_v2_qname_handle = undefined;
    try c.ok(v2.duckdb_v2_qname_parse(&text, &parsed, c.err()));
    defer _ = v2.duckdb_v2_qname_destroy(&parsed);

    var desc: v2.duckdb_v2_table_description_handle = undefined;
    try c.ok(v2.duckdb_v2_connection_describe_table(s.conn, parsed, &desc, c.err()));
    defer _ = v2.duckdb_v2_table_description_destroy(&desc);

    var resolved: v2.duckdb_v2_qname_handle = undefined;
    try c.ok(v2.duckdb_v2_table_description_get_qname(desc, &resolved, c.err()));
    defer _ = v2.duckdb_v2_qname_destroy(&resolved);
    var readonly = false;
    try c.ok(v2.duckdb_v2_table_description_is_readonly(desc, &readonly, c.err()));
    var out: std.ArrayList(u8) = .empty;
    try out.print(arena, "{s}{s}:", .{ try qnameText(arena, resolved, &c), if (readonly) " (read-only)" else "" });

    var count: u64 = 0;
    try c.ok(v2.duckdb_v2_table_description_get_column_count(desc, &count, c.err()));
    for (0..count) |i| {
        var column: v2.duckdb_v2_column_description_handle = undefined;
        try c.ok(v2.duckdb_v2_table_description_get_column(desc, i, &column, c.err()));
        defer _ = v2.duckdb_v2_column_description_destroy(&column);
        var column_name: v2.duckdb_v2_identifier_t = undefined;
        try c.ok(v2.duckdb_v2_column_description_get_name(column, &column_name, c.err()));
        var ty: v2.duckdb_v2_logical_type_handle = undefined; // borrowed from the column: not destroyed
        try c.ok(v2.duckdb_v2_column_description_get_type(column, &ty, c.err()));
        var has_default = false;
        var generated = false;
        try c.ok(v2.duckdb_v2_column_description_has_default(column, &has_default, c.err()));
        try c.ok(v2.duckdb_v2_column_description_has_generated(column, &generated, c.err()));
        try out.print(arena, " {s} {s}{s}{s}", .{ view(column_name), try typeText(arena, ty, &c), if (has_default) " default" else "", if (generated) " generated" else "" });
    }
    return out.items;
}

fn catalog(arena: std.mem.Allocator) !void {
    var s = try Session.open();
    defer s.close();
    _ = try host.runAll(arena, &s,
        \\CREATE SCHEMA shop;
        \\CREATE TABLE shop.orders (
        \\    id INTEGER PRIMARY KEY,
        \\    Customer VARCHAR NOT NULL DEFAULT 'anonymous',
        \\    qty INTEGER DEFAULT 1,
        \\    price DECIMAL(9, 2),
        \\    total DECIMAL(12, 2) GENERATED ALWAYS AS (qty * price) VIRTUAL,
        \\    tags VARCHAR[]
        \\);
        \\CREATE VIEW shop.big_orders AS SELECT * FROM shop.orders WHERE qty > 10;
        \\CREATE TABLE main.plain (a BIGINT);
    );

    // The resolved name is complete and has the casing of the creation; columns come in declared order, generated ones
    // included, with their types as SQL writes them.
    try expectEqual("a schema-qualified name", "memory.shop.orders: id INTEGER Customer VARCHAR default qty INTEGER default price DECIMAL(9,2) total DECIMAL(12,2) generated tags VARCHAR[]", try describe(arena, &s, "shop.orders"));
    // A partial name resolves as it does in SQL: through the search path.
    try expectEqual("an unqualified name", "memory.main.plain: a BIGINT", try describe(arena, &s, "plain"));
    try expectFailure("a name outside the search path", describe(arena, &s, "orders"), .ERROR_DATABASE_CATALOG, "orders");
    _ = try host.runAll(arena, &s, "SET search_path = 'shop'");
    try expectEqual("the search path decides", "memory.shop.orders:", (try describe(arena, &s, "orders"))[0.."memory.shop.orders:".len]);

    // A view is not a table, and a name that is nothing is not found: the engine's own errors.
    try expectFailure("a view", describe(arena, &s, "shop.big_orders"), .ERROR_DATABASE_CATALOG, "");
    try expectFailure("no such table", describe(arena, &s, "shop.nothing"), .ERROR_DATABASE_CATALOG, "nothing");

    // A description is a snapshot: the table can go, and the description is still readable.
    var c: Call = .{};
    const name_text = str("main.plain");
    var parsed: v2.duckdb_v2_qname_handle = undefined;
    try c.ok(v2.duckdb_v2_qname_parse(&name_text, &parsed, c.err()));
    defer _ = v2.duckdb_v2_qname_destroy(&parsed);
    var desc: v2.duckdb_v2_table_description_handle = undefined;
    try c.ok(v2.duckdb_v2_connection_describe_table(s.conn, parsed, &desc, c.err()));
    defer _ = v2.duckdb_v2_table_description_destroy(&desc);
    _ = try host.runAll(arena, &s, "DROP TABLE main.plain");
    var count: u64 = 0;
    try c.ok(v2.duckdb_v2_table_description_get_column_count(desc, &count, c.err()));
    try expectInt("a snapshot outlives its table", 1, count);
}

// --- the audit ------------------------------------------------------------------------------------------------------------

/// The documentation of the functions of one extension, as numbers.
const Audit = struct { functions: u64 = 0, described: u64 = 0, with_examples: u64 = 0, with_categories: u64 = 0, placeholder_names: u64 = 0 };

/// Whether a parameter name is one of the placeholders: `col0` (v1, a plain function) or `a0` (a comptime function that was
/// not given names).
fn isPlaceholder(name: []const u8) bool {
    const digits = if (std.mem.startsWith(u8, name, "col")) name[3..] else if (std.mem.startsWith(u8, name, "a")) name[1..] else return false;
    if (digits.len == 0) return false;
    for (digits) |ch| if (!std.ascii.isDigit(ch)) return false;
    return true;
}

/// Counts over all the functions of the instance, per extension (by `extension_name`; none is a built-in), in Zig: the
/// aggregate and list functions that SQL would use are in `core_functions`, which this program does not link. Lists arrive as
/// their text, "[a, b]".
fn auditAll(arena: std.mem.Allocator, s: *Session) !std.StringArrayHashMapUnmanaged(Audit) {
    const rows = (try host.runAll(arena, s, "SELECT extension_name, description IS NOT NULL, CAST(examples AS VARCHAR), CAST(categories AS VARCHAR), CAST(parameters AS VARCHAR) FROM duckdb_functions()"))[0].rows;
    var by_extension: std.StringArrayHashMapUnmanaged(Audit) = .empty;
    for (rows) |row| {
        const entry = try by_extension.getOrPut(arena, if (std.mem.eql(u8, row[0], "NULL")) "(built in)" else row[0]);
        if (!entry.found_existing) entry.value_ptr.* = .{};
        const a = entry.value_ptr;
        a.functions += 1;
        if (std.mem.eql(u8, row[1], "true")) a.described += 1;
        if (!std.mem.eql(u8, row[2], "[]")) a.with_examples += 1;
        if (!std.mem.eql(u8, row[3], "[]")) a.with_categories += 1;
        const list = std.mem.trim(u8, row[4], "[]");
        var it = std.mem.splitSequence(u8, list, ", ");
        var placeholder = false;
        while (it.next()) |name| placeholder = placeholder or isPlaceholder(name);
        if (placeholder) a.placeholder_names += 1;
    }
    return by_extension;
}

fn printAudit(label: []const u8, a: Audit) void {
    std.debug.print("  {s:<34} {d:>5} functions {d:>5} described {d:>5} with examples {d:>5} with categories {d:>4} with col0/a0 names\n", .{ label, a.functions, a.described, a.with_examples, a.with_categories, a.placeholder_names });
}

fn audit(arena: std.mem.Allocator, v2_extension: []const u8, cookbook_extension: []const u8) !void {
    // Without `allow_unsigned_extensions` at startup an extension that is not signed does not load.
    {
        var plain = try Session.open();
        defer plain.close();
        const sql = try std.fmt.allocPrint(arena, "LOAD '{s}'", .{v2_extension});
        try expectFailure("an unsigned extension without the startup option", host.runAll(arena, &plain, sql), .ERROR_IO_GENERAL, "");
    }

    var names = [_]v2.duckdb_v2_str{str("allow_unsigned_extensions")};
    var values = [_]v2.duckdb_v2_str{str("true")};
    var s = try Session.openWithOptions(&names, &values);
    defer s.close();
    // `core_functions` is linked in (and registered), but loaded only when asked: some of the examples use its functions.
    _ = try host.runAll(arena, &s, "LOAD core_functions");
    inline for (.{ v2_extension, cookbook_extension }) |path| {
        _ = try host.runAll(arena, &s, try std.fmt.allocPrint(arena, "LOAD '{s}'", .{path}));
    }

    // Every extension of the instance, the built-in functions among them (a path for those loaded from a file).
    std.debug.print("documentation of the functions of this instance:\n", .{});
    const by_extension = try auditAll(arena, &s);
    for (by_extension.keys(), by_extension.values()) |label, a| {
        printAudit(if (std.mem.lastIndexOfScalar(u8, label, '/')) |i| label[i + 1 ..] else label, a);
    }

    inline for (.{ v2_extension, cookbook_extension }) |path| {
        const a = by_extension.get(path) orelse return error.ExtensionNotFound;
        try expectInt("functions in the extension", 1, @intFromBool(a.functions > 0));
        // The audit as a gate: nothing is left out, so a new function without docs fails here.
        try expectInt("every function is described", a.functions, a.described);
        try expectInt("every function has an example", a.functions, a.with_examples);
        try expectInt("every function has a category", a.functions, a.with_categories);
        try expectInt("no function has col0 or a0 for a parameter", 0, a.placeholder_names);

        // And every example runs. They are SQL text: one statement or several, each of them valid on its own.
        const examples = (try host.runAll(arena, &s, try std.fmt.allocPrint(arena, "SELECT DISTINCT unnest(examples) AS example FROM duckdb_functions() WHERE extension_name = '{s}' ORDER BY example", .{path})))[0];
        try expectInt("there are examples", 1, @intFromBool(examples.rows.len > 0));
        for (examples.rows) |row| _ = host.runAll(arena, &s, row[0]) catch |e| {
            std.debug.print("example failed: {s}\n", .{row[0]});
            return e;
        };
        std.debug.print("  ran {d} examples of {s}\n", .{ examples.rows.len, path });
    }
}
